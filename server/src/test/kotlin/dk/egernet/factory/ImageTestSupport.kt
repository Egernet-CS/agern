/**
 * An image provider for tests: records every call with the key it got, answers with PNGs of the requested size, and
 * can be told to fail with any [ImageProviderException] kind or to return other bytes.
 */
class RecordingImageProvider(
    override val id: String = "rec",
    override val label: String = "Recorder",
    override val supportsTransparency: Boolean = true,
) : ImageProvider {
    override val models = listOf("rec-1", "rec-2")
    override val defaultModel = "rec-1"
    override val keyPlaceholder = "rec-…"

    data class Call(val key: String, val model: String, val request: ImageRequest?)
    val validations = CopyOnWriteArrayList<Call>()
    val generations = CopyOnWriteArrayList<Call>()

    /** Validation: keys starting with `bad` are rejected, `down` is unreachable; model `nope` is unknown. */
    override fun validate(key: String, model: String) {
        validations += Call(key, model, null)
        if (key.startsWith("bad")) throw ImageProviderException(ImageProviderException.INVALID_CREDENTIAL)
        if (key.startsWith("down")) throw ImageProviderException(ImageProviderException.UNAVAILABLE)
        if (model == "nope") throw ImageProviderException(ImageProviderException.UNKNOWN_MODEL)
    }

    /** Set to make the next generations fail with this exception. */
    @Volatile var failWith: ImageProviderException? = null
    /** Set to replace the generated bytes. */
    @Volatile var answer: ((ImageRequest) -> List<ByteArray>)? = null

    override fun generate(key: String, model: String, request: ImageRequest): List<ByteArray> {
        generations += Call(key, model, request)
        failWith?.let { throw it }
        answer?.let { return it(request) }
        return (1..request.count).map { png(request.width, request.height, request.transparent) }
    }
}

/** MCP calls the way an agent makes them. */
object Mcp {
    data class Answer(val isError: Boolean, val text: String) {
        val json: JsonObject get() = AppJson.parseToJsonElement(text).jsonObject
    }

    fun token(p: FakeProcess): String = AppJson.parseToJsonElement(p.spec.mcpConfigJson).jsonObject["mcpServers"]!!.jsonObject["factory"]!!
        .jsonObject["headers"]!!.jsonObject["Authorization"]!!.jsonPrimitive.content.removePrefix("Bearer ")

    fun call(w: TestWorld, token: String, tool: String, args: JsonObject): Answer {
        val body = buildJsonObject {
            put("jsonrpc", "2.0"); put("id", 1); put("method", "tools/call")
            put("params", buildJsonObject { put("name", tool); put("arguments", args) })
        }
        val res = AppJson.parseToJsonElement(runBlocking { w.services.mcp.handle(token, body.toString()) }.second!!).jsonObject
        val r = res["result"]?.jsonObject ?: error("JSON-RPC error instead of a tool result: $res")
        return Answer(r["isError"]?.jsonPrimitive?.booleanOrNull == true, r["content"]!!.jsonArray[0].jsonObject["text"]!!.jsonPrimitive.content)
    }

    fun generate(w: TestWorld, token: String, args: JsonObject = buildJsonObject { put("prompt", "A squirrel icon"); put("purpose", "app icon") }) =
        call(w, token, "factory_generate_image", args)

    fun tools(w: TestWorld, token: String): List<String> =
        AppJson.parseToJsonElement(runBlocking { w.services.mcp.handle(token, """{"jsonrpc":"2.0","id":1,"method":"tools/list"}""") }.second!!)
            .jsonObject["result"]!!.jsonObject["tools"]!!.jsonArray.map { it.jsonObject["name"]!!.jsonPrimitive.content }
}

/** Stores [key] for [user] with the provider [provider] and model [model], as the Settings route would after validation. */
fun TestWorld.imageKey(user: String, key: String, provider: String = "rec", model: String = "rec-1") {
    val u = services.users.byUsername(user)!!
    services.users.setImageProvider(u.id, provider, model, services.box.encrypt(key, user))
}
